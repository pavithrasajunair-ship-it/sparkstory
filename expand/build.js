// Merges expand/*.json into story-expand.js (loaded by the story maker). Run: node expand/build.js
const fs = require("fs"), path = require("path");
const out = {};
for (const f of fs.readdirSync(__dirname).filter((f) => f.endsWith(".json")).sort()) out[f.replace(".json", "")] = JSON.parse(fs.readFileSync(path.join(__dirname, f), "utf8"));
const src = `/* Generated by expand/build.js from expand/*.json. Extra story paragraphs the maker weaves in to reach the chosen length. */
(function (root, factory) {
  if (typeof module === "object" && module.exports) module.exports = factory();
  else root.SSExpand = factory();
})(typeof self !== "undefined" ? self : this, function () {
  return ${JSON.stringify(out)};
});
`;
fs.writeFileSync(path.join(__dirname, "..", "story-expand.js"), src);
console.log("story-expand.js", (src.length / 1024).toFixed(0) + " KB");
